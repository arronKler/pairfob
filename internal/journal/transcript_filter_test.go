var injectedMarkers = []string{
	"local-command-caveat", "command-name", "command-message", "local-command-stdout", "system-reminder",
	"task-notification", "Request interrupted", "No response requested", "Summary of earlier work",
	"Base directory for this skill", "AGENTS.md", "Agent notes body", "environment_context", "turn_aborted",
	"codex_internal_context", "active thread goal", "question_reply", "questionItemId", "Which computer",
}

func assertNoInjected(t *testing.T, value any) {
	t.Helper()
	encoded, _ := json.Marshal(value)
	for _, marker := range injectedMarkers {
		if strings.Contains(string(encoded), marker) {
			t.Fatalf("injected %q leaked: %s", marker, encoded)
		}
	}
}

func claudeUser(content any, flags map[string]any) map[string]any {
	line := map[string]any{"type": "user", "message": map[string]any{"role": "user", "content": content}}
	for key, value := range flags {
		line[key] = value
	}
	return line
}

