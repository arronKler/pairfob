func TestStripTaggedBlocksKeepsUserText(t *testing.T) {
	cases := map[string]string{
		"see the <system-reminder> tag docs":                                         "see the <system-reminder> tag docs",
		"<system-reminder>\nunterminated user paste":                                 "<system-reminder>\nunterminated user paste",
		"keep\n<system-reminder>drop</system-reminder>\nthis":                        "keep\n\nthis",
		"<system-reminders>not ours</system-reminders>":                              "<system-reminders>not ours</system-reminders>",
		"  <system-reminder>a</system-reminder><system-reminder>b</system-reminder>": "  ",
	}
	for input, want := range cases {
		if got := stripTaggedBlocks(input, []string{"system-reminder"}); got != want {
			t.Fatalf("strip(%q)=%q want %q", input, got, want)
		}
	}
}

func TestInjectedTagsInsideTypedPromptsStayVisible(t *testing.T) {
	prompt := "Why does this render wrong?\n<command-name>/clear</command-name>\nplease fix"
	if event, ok := claudeUserEvent(prompt); !ok || event.Type != "user" || event.Text != prompt {
		t.Fatalf("command tags in a prompt: %+v", event)
	}
	shell := "Explain this fixture:\n<bash-input>ls</bash-input>"
	if event, ok := claudeUserEvent(shell); !ok || event.Type != "user" || event.Text != shell {
		t.Fatalf("bash tags in a prompt: %+v", event)
	}
	manifest := "Write a manifest like\n<skill>\n<name>x</name>\n</skill>\nthanks"
	if got := visibleCodexUserText(manifest); got != manifest {
		t.Fatalf("codex skill block in a prompt: %q", got)
	}
	injected := "<skill>\n<name>x</name>\n</skill>\n\nreal question"
	if got := visibleCodexUserText(injected); got != "real question" {
		t.Fatalf("leading injected skill: %q", got)
	}
}

