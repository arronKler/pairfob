func TestCodexDropsTheWholeInjectedAgentsFile(t *testing.T) {
	root := t.TempDir()
	id := "session_12345678"
	agents := "# AGENTS.md instructions for /tmp/repo\n\n<INSTRUCTIONS>\n# Agent notes\n\nAgent notes body\n\n## Section\n\nMore rules\n</INSTRUCTIONS>"
	writeLines(t, filepath.Join(root, "sessions", "2026", "10", "03", "rollout-"+id+".jsonl"),
		map[string]any{"type": "response_item", "payload": map[string]any{
			"type": "message", "role": "user", "content": []map[string]any{
				{"type": "input_text", "text": agents},
				{"type": "input_text", "text": "<environment_context>\n  <cwd>/tmp</cwd>\n</environment_context>"},
			},
		}},
		map[string]any{"type": "response_item", "payload": map[string]any{
			"type": "message", "role": "user", "content": []map[string]any{
				{"type": "input_text", "text": "<turn_aborted>\nThe user interrupted.\n</turn_aborted>"},
			},
		}},
		map[string]any{"type": "response_item", "payload": map[string]any{
			"type": "message", "role": "user", "content": []map[string]any{
				{"type": "input_text", "text": "<codex_internal_context source=\"goal\">\nContinue working toward the active thread goal.\n</codex_internal_context>"},
			},
		}},
		map[string]any{"type": "response_item", "payload": map[string]any{
			"type": "message", "role": "user", "content": []map[string]any{{"type": "input_text", "text": "fix the bug"}},
		}},
		map[string]any{"type": "response_item", "payload": map[string]any{
			"type": "message", "role": "user", "content": []map[string]any{{"type": "input_text", "text": "<send_user_message_question_reply>\n" +
				`[{"answer":"this Mac","question":"Which computer?","questionItemId":"[\"request_user_input_async\",\"call_1\",0]"}]` +
				"\n</send_user_message_question_reply>\n"}},
		}},
	)
	reader := &Reader{CodexRoot: root}
	ref := Ref{Source: "herdr:codex", Agent: "codex", Kind: "id", Value: id}
	trace, err := reader.ReadTrace(ref, nil, 20)
	if err != nil || len(trace.Items) != 2 || trace.Items[0].Text != "fix the bug" || trace.Items[1].Text != "this Mac" {
		t.Fatalf("trace=%+v err=%v", trace, err)
	}
	assertNoInjected(t, trace)
	history, err := reader.Read(ref, nil, 20)
	if err != nil || len(history.Messages) != 2 || history.Messages[0].Text != "fix the bug" || history.Messages[1].Text != "this Mac" {
		t.Fatalf("history=%+v err=%v", history, err)
	}
	assertNoInjected(t, history)
}

