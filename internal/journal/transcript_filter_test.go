func TestClaudeTraceShowsOnlyTypedPromptsAndAgentOutput(t *testing.T) {
	reader, ref := writeInjectedClaudeTranscript(t)
	page, err := reader.ReadTrace(ref, nil, 50)
	if err != nil {
		t.Fatal(err)
	}
	want := []Event{
		{Type: "user", Text: "/clear"},
		{Type: "user", Text: "why does it reconnect?"},
		{Type: "tool", Name: "Read", Input: `{"file_path":"/tmp/a"}`, Output: "file body"},
		{Type: "user", Text: "! git status"},
		{Type: "user", Text: "/model opus"},
		{Type: "assistant", Text: "Because the session expired."},
	}
	if len(page.Items) != len(want) {
		t.Fatalf("items=%+v", page.Items)
	}
	for i, item := range page.Items {
		if item.Type != want[i].Type || item.Text != want[i].Text || item.Name != want[i].Name || item.Input != want[i].Input || item.Output != want[i].Output {
			t.Fatalf("item %d=%+v want %+v", i, item, want[i])
		}
	}
	assertNoInjected(t, page)

	summary, err := reader.ReadTraceSummary(ref, nil, 50)
	if err != nil {
		t.Fatal(err)
	}
	detail, err := reader.ReadTraceDetail(ref, summary.Items[2].DetailRef)
	if err != nil || detail.Output != "file body" {
		t.Fatalf("detail=%+v err=%v", detail, err)
	}
}

func TestClaudeHistoryShowsOnlyTypedPromptsAndAgentOutput(t *testing.T) {
	reader, ref := writeInjectedClaudeTranscript(t)
	page, err := reader.Read(ref, nil, 50)
	if err != nil {
		t.Fatal(err)
	}
	texts := make([]string, 0, len(page.Messages))
	for _, message := range page.Messages {
		texts = append(texts, message.Role+":"+message.Text)
	}
	got := strings.Join(texts, "|")
	if got != "user:/clear|user:why does it reconnect?|assistant:工具 · Read|user:! git status|user:/model opus|assistant:Because the session expired." {
		t.Fatalf("history=%q", got)
	}
	assertNoInjected(t, page)
}

